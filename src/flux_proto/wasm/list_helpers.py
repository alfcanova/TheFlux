from __future__ import annotations

"""Colecao de helpers de list/set emitidos em binario (sem texto WAT).

Port direto das funcoes WAT em src/flux_proto/wat/list_helpers.py para o
emissor binario, preservando layout de memoria e semantica:

  cabecalho da lista:  +0 len, +4 cap, +8 etag, +12 data
  linha (row):         +0 tag (i32), +8 val (i64), 16 bytes
"""

from flux_proto.wasm.binary import (
    FuncBody, I32, I64, F64,
    OP_I32_LOAD, OP_I64_LOAD, OP_I32_LOAD8_U,
    OP_I32_STORE, OP_I64_STORE, OP_I32_STORE8,
    OP_I32_CONST, OP_I64_CONST,
    OP_I64_EQZ, OP_I32_EQZ, OP_I32_EQ, OP_I32_NE,
    OP_I64_EQ, OP_I64_NE, OP_I64_LT_U, OP_I64_GT_U, OP_I64_LE_U, OP_I64_GE_U,
    OP_I32_LT_U, OP_I32_GT_U, OP_I32_LE_U, OP_I32_GE_U,
    OP_I32_ADD, OP_I32_SUB, OP_I32_MUL, OP_I32_DIV_U, OP_I32_REM_U,
    OP_I32_AND, OP_I32_OR,
    OP_I64_ADD, OP_I64_SUB, OP_I64_MUL, OP_I64_OR,
    OP_I64_AND, OP_I64_XOR, OP_I64_REM_U,
    OP_I32_LT_S,
    OP_I64_SHL, OP_I64_SHR_U, OP_I64_EXTEND_I32_U, OP_I32_WRAP_I64,
    OP_I32_SHL, OP_I32_SHR_U,
    OP_I64_REINTERPRET_F64, OP_F64_REINTERPRET_I64,
    OP_F64_LT,
    OP_RETURN, OP_DROP, OP_SELECT, OP_IF, OP_ELSE, OP_END,
    OP_BR_IF, OP_BR, OP_BLOCK, OP_LOOP, OP_UNREACHABLE,
    OP_GLOBAL_GET, OP_GLOBAL_SET,
    encode_memarg,
)
from flux_proto.wasm.binary import BLOCK_VOID

I32L = bytes([I32])
I64L = bytes([I64])
VOID = BLOCK_VOID


def _mem(fb, op, align, off=0) -> None:
    fb.byte(op)
    fb.put(encode_memarg(align, off))


def _call(fb, idx) -> None:
    fb.byte(0x10)
    fb.uleb(idx)


def _br_depth(fb, pos) -> int:
    return fb.label_depth - pos


class CollectionHelpers:
    """Constroi as funcoes auxiliares de list/set e registra em cg._helper_funcs."""

    def __init__(self, cg) -> None:
        self.cg = cg
        self.mod = cg._mod
        self.helpers = cg._helper_funcs
        self._idx = 0

    def add(self, key, params, results) -> int:
        t = self.mod.add_type(params, results)
        fidx = self.mod.add_function(t)
        self.helpers[key] = fidx
        return fidx

    def add_code(self, fb) -> None:
        self.mod.add_code(fb.get_locals_decls(), fb.get_bytes())

    # ── acesso / mutacao de linhas ────────────────────────────────
    def build_len(self):
        fb = FuncBody(self._nparams["$list_len"])
        fb.local_get(0)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.byte(OP_RETURN)
        self.add_code(fb)
    def build_etag(self):
        fb = FuncBody(self._nparams["$list_etag"])
        fb.local_get(0)
        fb.i32_const(8)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.byte(OP_RETURN)
        self.add_code(fb)
    def build_row_addr(self):
        fb = FuncBody(self._nparams["$list_row_addr"])
        fb.local_get(0)
        fb.i32_const(12)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.local_get(1)
        fb.i32_const(1)
        fb.byte(OP_I32_SUB)
        fb.i32_const(16)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        fb.byte(OP_RETURN)
        self.add_code(fb)
    def build_row_tag(self):
        fb = FuncBody(self._nparams["$list_row_tag"])
        fb.local_get(0)
        fb.local_get(1)
        _call(fb, self.helpers["$list_row_addr"])
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.byte(OP_RETURN)
        self.add_code(fb)
    def build_row_val(self):
        fb = FuncBody(self._nparams["$list_row_val"])
        fb.local_get(0)
        fb.local_get(1)
        _call(fb, self.helpers["$list_row_addr"])
        fb.i32_const(8)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I64_LOAD, 3, 0)
        fb.byte(OP_RETURN)
        self.add_code(fb)
    def build_set_row(self):
        fb = FuncBody(self._nparams["$list_set_row"])
        addr = fb.new_i32()
        tag = fb.new_i32()
        fb.local_get(2)
        fb.local_set(tag)
        fb.local_get(tag)
        fb.byte(OP_I32_EQZ)
        fb.byte(OP_IF)
        fb.byte(VOID)
        fb.local_get(3)
        fb.i64_const(32)
        fb.byte(OP_I64_SHR_U)
        fb.byte(OP_I64_EQZ)
        fb.byte(OP_IF)
        fb.byte(VOID)
        fb.i32_const(1)
        fb.local_set(tag)
        fb.byte(OP_ELSE)
        fb.i32_const(4)
        fb.local_set(tag)
        fb.byte(OP_END)
        fb.byte(OP_END)
        fb.local_get(0)
        fb.local_get(1)
        _call(fb, self.helpers["$list_row_addr"])
        fb.local_set(addr)
        fb.local_get(addr)
        fb.local_get(tag)
        _mem(fb, OP_I32_STORE, 2, 0)
        fb.local_get(addr)
        fb.i32_const(8)
        fb.byte(OP_I32_ADD)
        fb.local_get(3)
        _mem(fb, OP_I64_STORE, 3, 0)
        self.add_code(fb)

    # ── alocacao / crescimento ────────────────────────────────────
    def build_flux_alloc(self):
        fb = FuncBody(self._nparams["$flux_alloc"])
        cur = fb.new_i32()
        newend = fb.new_i32()
        msize = fb.new_i32()
        npages = fb.new_i32()
        fb.global_get(self.cg._heap_global)
        fb.local_set(cur)
        # newend = cur + size
        fb.local_get(cur)
        fb.local_get(0)
        fb.byte(OP_I32_ADD)
        fb.local_set(newend)
        # msize = current_memory() * 65536  (memory.size -> i32 pages)
        fb.byte(0x3f)   # memory.size
        fb.byte(0x00)
        fb.i32_const(65536)
        fb.byte(OP_I32_MUL)
        fb.local_set(msize)
        # if newend > msize: grow pages needed
        fb.local_get(newend)
        fb.local_get(msize)
        fb.byte(OP_I32_GT_U)
        fb.byte(OP_IF)
        fb.byte(VOID)
        # needed = (newend - msize + 65535) >> 16
        fb.local_get(newend)
        fb.local_get(msize)
        fb.byte(OP_I32_SUB)
        fb.i32_const(65535)
        fb.byte(OP_I32_ADD)
        fb.i32_const(16)
        fb.byte(OP_I32_SHR_U)
        fb.local_set(npages)
        fb.local_get(npages)
        fb.byte(0x40)   # memory.grow
        fb.byte(0x00)
        fb.byte(OP_DROP)
        fb.byte(OP_END)
        # cur = cur (already set), update heap
        fb.local_get(newend)
        fb.global_set(self.cg._heap_global)
        fb.local_get(cur)
        fb.byte(OP_RETURN)
        self.add_code(fb)
    def build_build(self):
        fb = FuncBody(self._nparams["$list_build"])
        hdr = fb.new_i32()
        data = fb.new_i32()
        i = fb.new_i32()
        fb.i32_const(16)
        _call(fb, self.helpers["$flux_alloc"])
        fb.local_set(hdr)
        # bytes = select(n*16, 16, n > 0)
        fb.local_get(0)
        fb.i32_const(16)
        fb.byte(OP_I32_MUL)
        fb.i32_const(16)
        fb.local_get(0)
        fb.i32_const(0)
        fb.byte(OP_I32_GT_U)
        fb.byte(OP_SELECT)
        _call(fb, self.helpers["$flux_alloc"])
        fb.local_set(data)
        fb.local_get(hdr)
        fb.local_get(0)
        _mem(fb, OP_I32_STORE, 2, 0)
        fb.local_get(hdr)
        fb.i32_const(4)
        fb.byte(OP_I32_ADD)
        fb.local_get(0)
        _mem(fb, OP_I32_STORE, 2, 0)
        fb.local_get(hdr)
        fb.i32_const(8)
        fb.byte(OP_I32_ADD)
        fb.i32_const(0)
        _mem(fb, OP_I32_STORE, 2, 0)
        fb.local_get(hdr)
        fb.i32_const(12)
        fb.byte(OP_I32_ADD)
        fb.local_get(data)
        _mem(fb, OP_I32_STORE, 2, 0)
        fb.emit_block()
        done = fb.label_depth
        fb.emit_loop()
        loop = fb.label_depth
        fb.local_get(i)
        fb.local_get(0)
        fb.byte(OP_I32_GE_U)
        fb.br_if(_br_depth(fb, done))
        fb.local_get(data)
        fb.local_get(i)
        fb.i32_const(16)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        fb.i32_const(0)
        _mem(fb, OP_I32_STORE, 2, 0)
        fb.local_get(data)
        fb.local_get(i)
        fb.i32_const(16)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        fb.i32_const(8)
        fb.byte(OP_I32_ADD)
        fb.i64_const(0)
        _mem(fb, OP_I64_STORE, 3, 0)
        fb.local_get(i)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.local_set(i)
        fb.br(_br_depth(fb, loop))
        fb.emit_end()
        fb.emit_end()
        fb.local_get(hdr)
        fb.byte(OP_RETURN)
        self.add_code(fb)

    def build_concat(self):
        fb = FuncBody(self._nparams["$list_concat"])
        newc = fb.new_i32()
        la = fb.new_i32()
        lb = fb.new_i32()
        i = fb.new_i32()
        # la = len(a); lb = len(b)
        fb.local_get(0)
        fb.byte(OP_I32_LOAD)
        fb.put(encode_memarg(2, 0))
        fb.local_set(la)
        fb.local_get(1)
        fb.byte(OP_I32_LOAD)
        fb.put(encode_memarg(2, 0))
        fb.local_set(lb)
        # new = list_build(la+lb)
        fb.local_get(la)
        fb.local_get(lb)
        fb.byte(OP_I32_ADD)
        _call(fb, self.helpers["$list_build"])
        fb.local_set(newc)
        # copy a rows
        tag = fb.new_i32()
        val = fb.new_i64()
        fb.i32_const(1)
        fb.local_set(i)
        fb.emit_block()
        done_a = fb.label_depth
        fb.emit_loop()
        loop_a = fb.label_depth
        fb.local_get(i)
        fb.local_get(la)
        fb.byte(OP_I32_GT_U)
        fb.br_if(_br_depth(fb, done_a))
        fb.local_get(0)
        fb.local_get(i)
        _call(fb, self.helpers["$list_row_tag"])
        fb.local_set(tag)
        fb.local_get(0)
        fb.local_get(i)
        _call(fb, self.helpers["$list_row_val"])
        fb.local_set(val)
        fb.local_get(newc)
        fb.local_get(i)
        fb.local_get(tag)
        fb.local_get(val)
        _call(fb, self.helpers["$list_set_row"])
        # i++
        fb.local_get(i)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.local_set(i)
        fb.br(_br_depth(fb, loop_a))
        fb.emit_end()
        fb.emit_end()
        # copy b rows
        fb.i32_const(1)
        fb.local_set(i)
        fb.emit_block()
        done_b = fb.label_depth
        fb.emit_loop()
        loop_b = fb.label_depth
        fb.local_get(i)
        fb.local_get(lb)
        fb.byte(OP_I32_GT_U)
        fb.br_if(_br_depth(fb, done_b))
        fb.local_get(1)
        fb.local_get(i)
        _call(fb, self.helpers["$list_row_tag"])
        fb.local_set(tag)
        fb.local_get(1)
        fb.local_get(i)
        _call(fb, self.helpers["$list_row_val"])
        fb.local_set(val)
        fb.local_get(newc)
        fb.local_get(la)
        fb.local_get(i)
        fb.byte(OP_I32_ADD)
        fb.local_get(tag)
        fb.local_get(val)
        _call(fb, self.helpers["$list_set_row"])
        # i++
        fb.local_get(i)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.local_set(i)
        fb.br(_br_depth(fb, loop_b))
        fb.emit_end()
        fb.emit_end()
        fb.local_get(newc)
        fb.byte(OP_RETURN)
        self.add_code(fb)

    def build_grow(self):
        fb = FuncBody(self._nparams["$list_grow"])
        t = fb.new_i32()
        newcap = fb.new_i32()
        old = fb.new_i32()
        new = fb.new_i32()
        i = fb.new_i32()
        # t = cap*2; newcap = max(t, cap1); newcap = max(newcap, 8)
        fb.local_get(0)
        fb.i32_const(4)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.i32_const(2)
        fb.byte(OP_I32_MUL)
        fb.local_set(t)
        fb.local_get(t)
        fb.local_get(0)
        fb.i32_const(8)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.local_get(t)
        fb.local_get(0)
        fb.i32_const(8)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.byte(OP_I32_GE_U)
        fb.byte(OP_SELECT)
        fb.local_set(newcap)
        # newcap = select(newcap, 8, newcap >= 8)
        fb.local_get(newcap)
        fb.i32_const(8)
        fb.local_get(newcap)
        fb.i32_const(8)
        fb.byte(OP_I32_GE_U)
        fb.byte(OP_SELECT)
        fb.local_set(newcap)
        fb.local_get(0)
        fb.i32_const(12)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.local_set(old)
        fb.local_get(newcap)
        fb.i32_const(16)
        fb.byte(OP_I32_MUL)
        _call(fb, self.helpers["$flux_alloc"])
        fb.local_set(new)
        fb.emit_block()
        done = fb.label_depth
        fb.emit_loop()
        loop = fb.label_depth
        fb.local_get(i)
        fb.local_get(0)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.byte(OP_I32_GE_U)
        fb.br_if(_br_depth(fb, done))
        fb.local_get(new)
        fb.local_get(i)
        fb.i32_const(16)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        fb.local_get(old)
        fb.local_get(i)
        fb.i32_const(16)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I64_LOAD, 3, 0)
        _mem(fb, OP_I64_STORE, 3, 0)
        fb.local_get(new)
        fb.local_get(i)
        fb.i32_const(16)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        fb.i32_const(8)
        fb.byte(OP_I32_ADD)
        fb.local_get(old)
        fb.local_get(i)
        fb.i32_const(16)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        fb.i32_const(8)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I64_LOAD, 3, 0)
        _mem(fb, OP_I64_STORE, 3, 0)
        fb.local_get(i)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.local_set(i)
        fb.br(_br_depth(fb, loop))
        fb.emit_end()
        fb.emit_end()
        fb.local_get(0)
        fb.i32_const(12)
        fb.byte(OP_I32_ADD)
        fb.local_get(new)
        _mem(fb, OP_I32_STORE, 2, 0)
        fb.local_get(0)
        fb.i32_const(4)
        fb.byte(OP_I32_ADD)
        fb.local_get(newcap)
        _mem(fb, OP_I32_STORE, 2, 0)
        self.add_code(fb)

