    def build_i128_rem_u(self):
        fb = FuncBody(self._nparams["$i128_rem_u"])
        rem = fb.new_i64()
        i = fb.new_i32()
        bit = fb.new_i64()

        # if m == 0 -> return 0
        fb.local_get(2); fb.byte(OP_I64_EQZ)
        fb.emit_if()
        fb.i64_const(0); fb.byte(OP_RETURN)
        fb.emit_end()

        # if p_hi == 0 -> return p_lo % m (unsigned)
        fb.local_get(0); fb.byte(OP_I64_EQZ)
        fb.emit_if()
        fb.local_get(1); fb.local_get(2); fb.byte(OP_I64_REM_U); fb.byte(OP_RETURN)
        fb.emit_end()

        # if m == 9223372036854775807 (2^63 - 1)
        # fast path: 2^64 mod (2^63 - 1) = 2
        # rem = ((p_hi % m) * 2 + (p_lo % m)) % m
        fb.local_get(2); fb.i64_const(9223372036854775807); fb.byte(OP_I64_EQ)
        fb.emit_if()
        fb.local_get(0); fb.local_get(2); fb.byte(OP_I64_REM_U); fb.i64_const(2); fb.byte(OP_I64_MUL)
        fb.local_get(1); fb.local_get(2); fb.byte(OP_I64_REM_U); fb.byte(OP_I64_ADD)
        fb.local_get(2); fb.byte(OP_I64_REM_U); fb.byte(OP_RETURN)
        fb.emit_end()

        # Full bitwise long division:
        fb.i64_const(0); fb.local_set(rem)

        # High 64 bits (63 down to 0)
        fb.i32_const(63); fb.local_set(i)
        fb.emit_block()
        done_hi = fb.label_depth
        fb.emit_loop()
        loop_hi = fb.label_depth
        fb.local_get(i); fb.i32_const(0); fb.byte(OP_I32_LT_S)
        fb.br_if(_br_depth(fb, done_hi))

        # bit = (p_hi >> i) & 1
        fb.local_get(0); fb.local_get(i); fb.byte(OP_I64_EXTEND_I32_U); fb.byte(OP_I64_SHR_U); fb.i64_const(1); fb.byte(OP_I64_AND); fb.local_set(bit)
        # rem = (rem << 1) | bit
        fb.local_get(rem); fb.i64_const(1); fb.byte(OP_I64_SHL); fb.local_get(bit); fb.byte(OP_I64_OR); fb.local_set(rem)
        # if rem >= m: rem -= m
        fb.local_get(rem); fb.local_get(2); fb.byte(OP_I64_GE_U)
        fb.emit_if()
        fb.local_get(rem); fb.local_get(2); fb.byte(OP_I64_SUB); fb.local_set(rem)
        fb.emit_end()

        fb.local_get(i); fb.i32_const(1); fb.byte(OP_I32_SUB); fb.local_set(i)
        fb.br(_br_depth(fb, loop_hi))
        fb.emit_end()
        fb.emit_end()

        # Low 64 bits (63 down to 0)
        fb.i32_const(63); fb.local_set(i)
        fb.emit_block()
        done_lo = fb.label_depth
        fb.emit_loop()
        loop_lo = fb.label_depth
        fb.local_get(i); fb.i32_const(0); fb.byte(OP_I32_LT_S)
        fb.br_if(_br_depth(fb, done_lo))

        # bit = (p_lo >> i) & 1
        fb.local_get(1); fb.local_get(i); fb.byte(OP_I64_EXTEND_I32_U); fb.byte(OP_I64_SHR_U); fb.i64_const(1); fb.byte(OP_I64_AND); fb.local_set(bit)
        # rem = (rem << 1) | bit
        fb.local_get(rem); fb.i64_const(1); fb.byte(OP_I64_SHL); fb.local_get(bit); fb.byte(OP_I64_OR); fb.local_set(rem)
        # if rem >= m: rem -= m
        fb.local_get(rem); fb.local_get(2); fb.byte(OP_I64_GE_U)
        fb.emit_if()
        fb.local_get(rem); fb.local_get(2); fb.byte(OP_I64_SUB); fb.local_set(rem)
        fb.emit_end()

        fb.local_get(i); fb.i32_const(1); fb.byte(OP_I32_SUB); fb.local_set(i)
        fb.br(_br_depth(fb, loop_lo))
        fb.emit_end()
        fb.emit_end()

        fb.local_get(rem)
        fb.byte(OP_RETURN)
        self.add_code(fb)

