    def build_tensor_mat(self):
        fb = FuncBody(self._nparams["$tensor_mat"])
        rank = fb.new_i32()
        hdr = fb.new_i32()
        prod = fb.new_i32()
        k = fb.new_i32()
        d = fb.new_i32()
        sd = fb.new_i32()
        dst = fb.new_i32()
        L = fb.new_i32()
        soff = fb.new_i32()
        sdst = fb.new_i32()

        # rank = i32.load(src)
        fb.local_get(0)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.local_set(rank)

        # hdr = (rank + 1) * 8
        fb.local_get(rank)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.i32_const(8)
        fb.byte(OP_I32_MUL)
        fb.local_set(hdr)

        # prod = 1
        fb.i32_const(1)
        fb.local_set(prod)

        # prod loop
        fb.emit_block()
        done_p = fb.label_depth
        fb.emit_loop()
        loop_p = fb.label_depth

        fb.local_get(k)
        fb.local_get(rank)
        fb.byte(OP_I32_GE_U)
        fb.br_if(_br_depth(fb, done_p))

        # prod = prod * i32.load(src + (k + 1) * 4)
        fb.local_get(prod)
        fb.local_get(0)
        fb.local_get(k)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.i32_const(4)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.byte(OP_I32_MUL)
        fb.local_set(prod)

        fb.local_get(k)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.local_set(k)
        fb.br(_br_depth(fb, loop_p))
        fb.emit_end()
        fb.emit_end()

        # dst = flux_alloc(hdr + prod * 8)
        fb.local_get(hdr)
        fb.local_get(prod)
        fb.i32_const(8)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        _call(fb, self.helpers["$flux_alloc"])
        fb.local_set(dst)

        # store(dst, rank)
        fb.local_get(dst)
        fb.local_get(rank)
        _mem(fb, OP_I32_STORE, 2, 0)

        # sdst = 1; k = rank
        fb.i32_const(1)
        fb.local_set(sdst)
        fb.local_get(rank)
        fb.local_set(k)

        # strides loop (backwards)
        fb.emit_block()
        done_s = fb.label_depth
        fb.emit_loop()
        loop_s = fb.label_depth

        fb.local_get(k)
        fb.byte(OP_I32_EQZ)
        fb.br_if(_br_depth(fb, done_s))

        fb.local_get(k)
        fb.i32_const(1)
        fb.byte(OP_I32_SUB)
        fb.local_set(k)

        # d = i32.load(src + (k + 1) * 4)
        fb.local_get(0)
        fb.local_get(k)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.i32_const(4)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.local_set(d)

        # store(dst + (k + 1) * 4, d)
        fb.local_get(dst)
        fb.local_get(k)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.i32_const(4)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        fb.local_get(d)
        _mem(fb, OP_I32_STORE, 2, 0)

        # store(dst + (rank + k + 1) * 4, sdst)
        fb.local_get(dst)
        fb.local_get(rank)
        fb.local_get(k)
        fb.byte(OP_I32_ADD)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.i32_const(4)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        fb.local_get(sdst)
        _mem(fb, OP_I32_STORE, 2, 0)

        # sdst = sdst * d
        fb.local_get(sdst)
        fb.local_get(d)
        fb.byte(OP_I32_MUL)
        fb.local_set(sdst)

        fb.br(_br_depth(fb, loop_s))
        fb.emit_end()
        fb.emit_end()

        # store(dst + (rank * 2 + 1) * 4, dst + hdr)
        fb.local_get(dst)
        fb.local_get(rank)
        fb.i32_const(2)
        fb.byte(OP_I32_MUL)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.i32_const(4)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        fb.local_get(dst)
        fb.local_get(hdr)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_STORE, 2, 0)

        # copy data loop
        fb.i32_const(0)
        fb.local_set(L)

        fb.emit_block()
        done_c = fb.label_depth
        fb.emit_loop()
        loop_c = fb.label_depth

        fb.local_get(L)
        fb.local_get(prod)
        fb.byte(OP_I32_GE_U)
        fb.br_if(_br_depth(fb, done_c))

        fb.i32_const(0)
        fb.local_set(soff)
        fb.i32_const(0)
        fb.local_set(k)

        # kd loop
        fb.emit_block()
        done_k = fb.label_depth
        fb.emit_loop()
        loop_k = fb.label_depth

        fb.local_get(k)
        fb.local_get(rank)
        fb.byte(OP_I32_GE_U)
        fb.br_if(_br_depth(fb, done_k))

        # sd = i32.load(src + (rank + k + 1) * 4)
        fb.local_get(0)
        fb.local_get(rank)
        fb.local_get(k)
        fb.byte(OP_I32_ADD)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.i32_const(4)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.local_set(sd)

        # soff = soff + ((L / sd) % src_dim_k) * sd
        fb.local_get(soff)
        fb.local_get(L)
        fb.local_get(sd)
        fb.byte(OP_I32_DIV_U)
        fb.local_get(0)
        fb.local_get(k)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.i32_const(4)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.byte(OP_I32_REM_U)
        fb.local_get(sd)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        fb.local_set(soff)

        fb.local_get(k)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.local_set(k)
        fb.br(_br_depth(fb, loop_k))
        fb.emit_end()
        fb.emit_end()

        # i64.store(dst + hdr + L * 8, i64.load(src_dptr + soff * 8))
        fb.local_get(dst)
        fb.local_get(hdr)
        fb.byte(OP_I32_ADD)
        fb.local_get(L)
        fb.i32_const(8)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)

        fb.local_get(0)
        fb.local_get(rank)
        fb.i32_const(2)
        fb.byte(OP_I32_MUL)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.i32_const(4)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD, 2, 0)
        fb.local_get(soff)
        fb.i32_const(8)
        fb.byte(OP_I32_MUL)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I64_LOAD, 3, 0)

        _mem(fb, OP_I64_STORE, 3, 0)

        fb.local_get(L)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.local_set(L)
        fb.br(_br_depth(fb, loop_c))
        fb.emit_end()
        fb.emit_end()

        # return dst
        fb.local_get(dst)
        fb.byte(OP_RETURN)
        self.add_code(fb)

    # ── 128-bit math helpers para hashes e modulos grandes ─────────
    def build_i64_mul_128(self):
        fb = FuncBody(self._nparams["$i64_mul_128"])
        a_lo = fb.new_i64(); a_hi = fb.new_i64()
        b_lo = fb.new_i64(); b_hi = fb.new_i64()
        p0 = fb.new_i64(); p1 = fb.new_i64(); p2 = fb.new_i64(); p3 = fb.new_i64()
        mid = fb.new_i64(); p_lo = fb.new_i64(); p_hi = fb.new_i64()

        # a_lo = a & 0xFFFFFFFF
        fb.local_get(0); fb.i64_const(4294967295); fb.byte(OP_I64_AND); fb.local_set(a_lo)
        # a_hi = a >> 32
        fb.local_get(0); fb.i64_const(32); fb.byte(OP_I64_SHR_U); fb.local_set(a_hi)
        # b_lo = b & 0xFFFFFFFF
        fb.local_get(1); fb.i64_const(4294967295); fb.byte(OP_I64_AND); fb.local_set(b_lo)
        # b_hi = b >> 32
        fb.local_get(1); fb.i64_const(32); fb.byte(OP_I64_SHR_U); fb.local_set(b_hi)

        # p0 = a_lo * b_lo
        fb.local_get(a_lo); fb.local_get(b_lo); fb.byte(OP_I64_MUL); fb.local_set(p0)
        # p1 = a_lo * b_hi
        fb.local_get(a_lo); fb.local_get(b_hi); fb.byte(OP_I64_MUL); fb.local_set(p1)
        # p2 = a_hi * b_lo
        fb.local_get(a_hi); fb.local_get(b_lo); fb.byte(OP_I64_MUL); fb.local_set(p2)
        # p3 = a_hi * b_hi
        fb.local_get(a_hi); fb.local_get(b_hi); fb.byte(OP_I64_MUL); fb.local_set(p3)

        # mid = (p0 >> 32) + (p1 & 0xFFFFFFFF) + (p2 & 0xFFFFFFFF)
        fb.local_get(p0); fb.i64_const(32); fb.byte(OP_I64_SHR_U)
        fb.local_get(p1); fb.i64_const(4294967295); fb.byte(OP_I64_AND); fb.byte(OP_I64_ADD)
        fb.local_get(p2); fb.i64_const(4294967295); fb.byte(OP_I64_AND); fb.byte(OP_I64_ADD)
        fb.local_set(mid)

        # p_lo = (p0 & 0xFFFFFFFF) | ((mid & 0xFFFFFFFF) << 32)
        fb.local_get(p0); fb.i64_const(4294967295); fb.byte(OP_I64_AND)
        fb.local_get(mid); fb.i64_const(4294967295); fb.byte(OP_I64_AND); fb.i64_const(32); fb.byte(OP_I64_SHL)
        fb.byte(OP_I64_OR); fb.local_set(p_lo)

        # p_hi = p3 + (p1 >> 32) + (p2 >> 32) + (mid >> 32)
        fb.local_get(p3)
        fb.local_get(p1); fb.i64_const(32); fb.byte(OP_I64_SHR_U); fb.byte(OP_I64_ADD)
        fb.local_get(p2); fb.i64_const(32); fb.byte(OP_I64_SHR_U); fb.byte(OP_I64_ADD)
