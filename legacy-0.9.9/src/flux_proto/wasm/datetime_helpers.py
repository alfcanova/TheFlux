        fb = FuncBody(1)
        fb.local_get(0)
        fb.i64_const(400)
        fb.byte(OP_I64_REM_S)
        fb.byte(OP_I64_EQZ)
        fb.emit_if()
        fb.i64_const(1)
        fb.byte(OP_RETURN)
        fb.emit_end()

        fb.local_get(0)
        fb.i64_const(100)
        fb.byte(OP_I64_REM_S)
        fb.byte(OP_I64_EQZ)
        fb.emit_if()
        fb.i64_const(0)
        fb.byte(OP_RETURN)
        fb.emit_end()

        fb.local_get(0)
        fb.i64_const(4)
        fb.byte(OP_I64_REM_S)
        fb.byte(OP_I64_EQZ)
        fb.emit_if()
        fb.i64_const(1)
        fb.byte(OP_RETURN)
        fb.emit_end()

        fb.i64_const(0)
        fb.byte(OP_RETURN)
