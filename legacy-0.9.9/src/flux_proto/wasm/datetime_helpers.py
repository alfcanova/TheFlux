    def build_dt_parse_iso(self) -> None:
        fb = FuncBody(1)
        ptr = fb.new_i32()
        len_v = fb.new_i32()
        c = fb.new_i32()
        cneg = fb.new_i32()
        y = fb.new_i64()
        mo = fb.new_i64()
        d = fb.new_i64()
        h = fb.new_i64()
        mi = fb.new_i64()
        s = fb.new_i64()
        nanos = fb.new_i64()
        delta = fb.new_i64()
        secs = fb.new_i64()
        day = fb.new_i64()

        dt_pos = self.cg._dt_pos
        dt_ok = self.cg._dt_ok

        fb.local_get(0)
        fb.i64_const(32)
        fb.byte(OP_I64_SHR_U)
        fb.byte(OP_I32_WRAP_I64)
        fb.local_set(ptr)

        fb.local_get(0)
        fb.i64_const(0xFFFFFFFF)
        fb.byte(OP_I64_AND)
        fb.byte(OP_I32_WRAP_I64)
        fb.local_set(len_v)

        fb.i32_const(0)
        fb.global_set(dt_pos)
        fb.i32_const(1)
        fb.global_set(dt_ok)

        # Skip leading whitespace
        fb.emit_block()
        b_ws = fb.label_depth
        fb.emit_loop()
        l_ws = fb.label_depth
        fb.global_get(dt_pos)
        fb.local_get(len_v)
        fb.byte(OP_I32_GE_U)
        fb.br_if(_br_depth(fb, b_ws))
        fb.local_get(ptr)
        fb.global_get(dt_pos)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD8_U, 0, 0)
        fb.local_set(c)
        fb.local_get(c)
        fb.i32_const(32)
        fb.byte(OP_I32_EQ)
        fb.local_get(c)
        fb.i32_const(9)
        fb.byte(OP_I32_EQ)
        fb.byte(OP_I32_OR)
        fb.emit_if()
        fb.global_get(dt_pos)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.global_set(dt_pos)
        fb.br(_br_depth(fb, l_ws))
        fb.emit_else()
        fb.br(_br_depth(fb, b_ws))
        fb.emit_end()
        fb.emit_end()
        fb.emit_end()

        fb.i64_const(0)
        fb.local_set(nanos)
        fb.i64_const(0)
        fb.local_set(delta)

        # YYYY-
        fb.local_get(ptr)
        fb.local_get(len_v)
        fb.i32_const(4)
        fb.i32_const(45)
        _call(fb, self.helpers["$dt_num"])
        fb.local_set(y)

        # MM-
        fb.local_get(ptr)
        fb.local_get(len_v)
        fb.i32_const(2)
        fb.i32_const(45)
        _call(fb, self.helpers["$dt_num"])
        fb.local_set(mo)

        # DD with 'T' (84) or fallback to ' ' (32)
        fb.local_get(ptr)
        fb.local_get(len_v)
        fb.i32_const(2)
        fb.i32_const(84)
        _call(fb, self.helpers["$dt_num"])
        fb.local_set(d)

        fb.global_get(dt_ok)
        fb.byte(OP_I32_EQZ)
        fb.emit_if()
        fb.global_get(dt_pos)
        fb.i32_const(1)
        fb.byte(OP_I32_SUB)
        fb.global_set(dt_pos)
        fb.global_get(dt_pos)
        fb.local_get(len_v)
        fb.byte(OP_I32_LT_U)
        fb.emit_if()
        fb.local_get(ptr)
        fb.global_get(dt_pos)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD8_U, 0, 0)
        fb.local_set(c)
        fb.local_get(c)
        fb.i32_const(32)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.i32_const(1)
        fb.global_set(dt_ok)
        fb.global_get(dt_pos)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.global_set(dt_pos)
        fb.emit_end()
        fb.emit_end()
        fb.emit_end()

        # HH:
        fb.local_get(ptr)
        fb.local_get(len_v)
        fb.i32_const(2)
        fb.i32_const(58)
        _call(fb, self.helpers["$dt_num"])
        fb.local_set(h)

        # MM:
        fb.local_get(ptr)
        fb.local_get(len_v)
        fb.i32_const(2)
        fb.i32_const(58)
        _call(fb, self.helpers["$dt_num"])
        fb.local_set(mi)

        # SS
        fb.local_get(ptr)
        fb.local_get(len_v)
        fb.i32_const(2)
        _call(fb, self.helpers["$dt_num0"])
        fb.local_set(s)

        # Fractional seconds
        fb.global_get(dt_ok)
        fb.emit_if()
        fb.global_get(dt_pos)
        fb.local_get(len_v)
        fb.byte(OP_I32_LT_U)
        fb.emit_if()
        fb.local_get(ptr)
        fb.global_get(dt_pos)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD8_U, 0, 0)
        fb.local_set(c)
        fb.local_get(c)
        fb.i32_const(46)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.global_get(dt_pos)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.global_set(dt_pos)
        fb.local_get(ptr)
        fb.local_get(len_v)
        _call(fb, self.helpers["$dt_frac"])
        fb.local_set(nanos)
        fb.emit_end()
        fb.emit_end()
        fb.emit_end()

        # Timezone offset ('Z', '+', '-')
        fb.global_get(dt_ok)
        fb.emit_if()
        fb.global_get(dt_pos)
        fb.local_get(len_v)
        fb.byte(OP_I32_LT_U)
        fb.emit_if()
        fb.local_get(ptr)
        fb.global_get(dt_pos)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD8_U, 0, 0)
        fb.local_set(c)
        fb.local_get(c)
        fb.i32_const(90)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.global_get(dt_pos)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.global_set(dt_pos)
        fb.emit_else()
        fb.local_get(c)
        fb.i32_const(43)
        fb.byte(OP_I32_EQ)
        fb.local_get(c)
        fb.i32_const(45)
        fb.byte(OP_I32_EQ)
        fb.byte(OP_I32_OR)
        fb.emit_if()
        fb.i32_const(1)
        fb.i32_const(0)
        fb.local_get(c)
        fb.i32_const(45)
        fb.byte(OP_I32_EQ)
        fb.byte(OP_SELECT)
        fb.local_set(cneg)
        fb.global_get(dt_pos)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.global_set(dt_pos)
        fb.local_get(ptr)
        fb.local_get(len_v)
        fb.local_get(cneg)
        _call(fb, self.helpers["$dt_offset"])
        fb.local_set(delta)
        fb.emit_end()
        fb.emit_end()
        fb.emit_end()
        fb.emit_end()

        # Skip trailing whitespace
        fb.emit_block()
        b_tws = fb.label_depth
        fb.emit_loop()
        l_tws = fb.label_depth
        fb.global_get(dt_pos)
        fb.local_get(len_v)
        fb.byte(OP_I32_GE_U)
        fb.br_if(_br_depth(fb, b_tws))
        fb.local_get(ptr)
        fb.global_get(dt_pos)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD8_U, 0, 0)
        fb.local_set(c)
        fb.local_get(c)
        fb.i32_const(32)
        fb.byte(OP_I32_EQ)
        fb.local_get(c)
        fb.i32_const(9)
        fb.byte(OP_I32_EQ)
        fb.byte(OP_I32_OR)
        fb.emit_if()
        fb.global_get(dt_pos)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.global_set(dt_pos)
        fb.br(_br_depth(fb, l_tws))
        fb.emit_else()
        fb.br(_br_depth(fb, b_tws))
        fb.emit_end()
        fb.emit_end()
        fb.emit_end()

        # Verify end of string reached
        fb.global_get(dt_ok)
        fb.emit_if()
        fb.global_get(dt_pos)
        fb.local_get(len_v)
        fb.byte(OP_I32_NE)
        fb.emit_if()
        fb.i32_const(0)
        fb.global_set(dt_ok)
        fb.emit_end()
        fb.emit_end()

        fb.global_get(dt_ok)
        fb.byte(OP_I32_EQZ)
        fb.emit_if()
        fb.i64_const(0)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # day = days_from_civil(y, mo, d)
        fb.local_get(y)
        fb.local_get(mo)
        fb.local_get(d)
        _call(fb, self.helpers["$days_from_civil"])
        fb.local_set(day)

        # secs = day * 86400 + h * 3600 + mi * 60 + s - delta
        fb.local_get(day)
        fb.i64_const(86400)
        fb.byte(OP_I64_MUL)
        fb.local_get(h)
        fb.i64_const(3600)
        fb.byte(OP_I64_MUL)
        fb.byte(OP_I64_ADD)
        fb.local_get(mi)
        fb.i64_const(60)
        fb.byte(OP_I64_MUL)
        fb.byte(OP_I64_ADD)
        fb.local_get(s)
        fb.byte(OP_I64_ADD)
        fb.local_get(delta)
        fb.byte(OP_I64_SUB)
        fb.local_set(secs)

        # return secs * 1000000000 + nanos
        fb.local_get(secs)
        fb.i64_const(1000000000)
        fb.byte(OP_I64_MUL)
        fb.local_get(nanos)
        fb.byte(OP_I64_ADD)
        fb.byte(OP_RETURN)
        self.add_code(fb)

