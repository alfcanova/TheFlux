from __future__ import annotations

"""DateTime helper functions for WASM binary backend.

Direct port of the WAT DateTime helpers to the binary emitter.
"""

from flux_proto.wasm.binary import (
    FuncBody, I32, I64, F64,
    OP_I32_LOAD8_U, OP_I64_LOAD, OP_I32_STORE8,
    OP_I32_CONST, OP_I64_CONST, OP_F64_CONST,
    OP_I32_EQZ, OP_I32_EQ, OP_I32_NE,
    OP_I64_EQZ, OP_I64_EQ, OP_I64_NE,
    OP_I64_LT_S, OP_I64_LT_U, OP_I64_GT_S, OP_I64_GT_U, OP_I64_LE_S, OP_I64_GE_S,
    OP_I32_LT_U, OP_I32_GE_U, OP_I32_ADD, OP_I32_SUB, OP_I32_MUL, OP_I32_AND, OP_I32_OR,
    OP_I64_ADD, OP_I64_SUB, OP_I64_MUL, OP_I64_DIV_S, OP_I64_DIV_U,
    OP_I64_REM_S, OP_I64_REM_U, OP_I64_AND, OP_I64_OR, OP_I64_SHL, OP_I64_SHR_U,
    OP_I64_EXTEND_I32_U, OP_I32_WRAP_I64,
    OP_RETURN, OP_DROP, OP_SELECT, OP_IF, OP_ELSE, OP_END,
    OP_BR, OP_BR_IF,
    encode_memarg, sleb128,
)


def _mem(fb: FuncBody, op: int, align: int, off: int = 0) -> None:
    fb.byte(op)
    fb.put(encode_memarg(align, off))


def _call(fb: FuncBody, idx: int) -> None:
    fb.byte(0x10)
    fb.uleb(idx)


def _br_depth(fb: FuncBody, pos: int) -> int:
    return fb.label_depth - pos


class DateTimeHelpers:
    """Constructs DateTime helper functions for the WASM module."""

    def __init__(self, cg) -> None:
        self.cg = cg
        self.mod = cg._mod
        self.helpers = cg._helper_funcs

        zero_i64 = bytes([OP_I64_CONST]) + sleb128(0)
        self.g_y = self.mod.add_global(I64, True, zero_i64)
        self.g_m = self.mod.add_global(I64, True, zero_i64)
        self.g_d = self.mod.add_global(I64, True, zero_i64)
        self.g_h = self.mod.add_global(I64, True, zero_i64)
        self.g_mi = self.mod.add_global(I64, True, zero_i64)
        self.g_s = self.mod.add_global(I64, True, zero_i64)
        self.g_ms = self.mod.add_global(I64, True, zero_i64)
        self.g_us = self.mod.add_global(I64, True, zero_i64)
        self.g_ns = self.mod.add_global(I64, True, zero_i64)
        self.g_days = self.mod.add_global(I64, True, zero_i64)

    def add(self, key: str, params: list[int], results: list[int]) -> int:
        t = self.mod.add_type(params, results)
        fidx = self.mod.add_function(t)
        self.helpers[key] = fidx
        return fidx

    def add_code(self, fb: FuncBody) -> None:
        self.mod.add_code(fb.get_locals_decls(), fb.get_bytes())

    def build_dt_floor_div(self) -> None:
        fb = FuncBody(2)
        q = fb.new_i64()
        r = fb.new_i64()
        fb.local_get(0)
        fb.local_get(1)
        fb.byte(OP_I64_DIV_S)
        fb.local_set(q)
        fb.local_get(0)
        fb.local_get(1)
        fb.byte(OP_I64_REM_S)
        fb.local_set(r)
        fb.local_get(0)
        fb.i64_const(0)
        fb.byte(OP_I64_LT_S)
        fb.local_get(r)
        fb.i64_const(0)
        fb.byte(OP_I64_NE)
        fb.byte(OP_I32_AND)
        fb.emit_if()
        fb.local_get(q)
        fb.i64_const(1)
        fb.byte(OP_I64_SUB)
        fb.local_set(q)
        fb.emit_end()
        fb.local_get(q)
        fb.byte(OP_RETURN)
        self.add_code(fb)

    def build_dt_floor_rem(self) -> None:
        fb = FuncBody(2)
        fb.local_get(0)
        fb.local_get(0)
        fb.local_get(1)
        _call(fb, self.helpers["$dt_floor_div"])
        fb.local_get(1)
        fb.byte(OP_I64_MUL)
        fb.byte(OP_I64_SUB)
        fb.byte(OP_RETURN)
        self.add_code(fb)

