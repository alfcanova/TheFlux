        fb.local_set(cur)
        fb.local_get(buf)
        fb.local_get(cur)
        fb.byte(OP_I32_ADD)
        fb.i32_const(109)
        _mem(fb, OP_I32_STORE8, 0, 0)
        fb.local_get(buf)
        fb.local_get(cur)
