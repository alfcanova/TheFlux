    def build_dt_months_between(self) -> None:
        fb = FuncBody(2)
        left = 0
        right = 1
        sign = fb.new_i64()
        tmp = fb.new_i64()
        ly = fb.new_i64()
        lm = fb.new_i64()
        ld = fb.new_i64()
        lh = fb.new_i64()
        lmi = fb.new_i64()
        ls = fb.new_i64()
        lfrac = fb.new_i64()
        ry = fb.new_i64()
        rm = fb.new_i64()
        rd = fb.new_i64()
        rh = fb.new_i64()
        rmi = fb.new_i64()
        rs = fb.new_i64()
        rfrac = fb.new_i64()
        mdiff = fb.new_i64()
        less = fb.new_i32()

        # if left == right: return 0
        fb.local_get(left)
        fb.local_get(right)
        fb.byte(OP_I64_EQ)
        fb.emit_if()
        fb.i64_const(0)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # if right >= left: sign = 1 else sign = -1; swap(left, right)
        fb.local_get(right)
        fb.local_get(left)
        fb.byte(OP_I64_GE_S)
        fb.emit_if()
        fb.i64_const(1)
        fb.local_set(sign)
        fb.emit_else()
        fb.i64_const(-1)
        fb.local_set(sign)
        fb.local_get(left)
        fb.local_set(tmp)
        fb.local_get(right)
        fb.local_set(left)
        fb.local_get(tmp)
        fb.local_set(right)
        fb.emit_end()

        # dt_split(left)
        fb.local_get(left)
        _call(fb, self.helpers["$dt_split"])
        fb.global_get(self.g_y)
        fb.local_set(ly)
        fb.global_get(self.g_m)
        fb.local_set(lm)
        fb.global_get(self.g_d)
        fb.local_set(ld)
        fb.global_get(self.g_h)
        fb.local_set(lh)
        fb.global_get(self.g_mi)
        fb.local_set(lmi)
        fb.global_get(self.g_s)
        fb.local_set(ls)
        fb.global_get(self.g_ns)
        fb.local_set(lfrac)

        # dt_split(right)
        fb.local_get(right)
        _call(fb, self.helpers["$dt_split"])
        fb.global_get(self.g_y)
        fb.local_set(ry)
        fb.global_get(self.g_m)
        fb.local_set(rm)
        fb.global_get(self.g_d)
        fb.local_set(rd)
        fb.global_get(self.g_h)
        fb.local_set(rh)
        fb.global_get(self.g_mi)
        fb.local_set(rmi)
        fb.global_get(self.g_s)
        fb.local_set(rs)
        fb.global_get(self.g_ns)
        fb.local_set(rfrac)

        # mdiff = (ry * 12 + rm) - (ly * 12 + lm)
        fb.local_get(ry)
        fb.i64_const(12)
        fb.byte(OP_I64_MUL)
        fb.local_get(rm)
        fb.byte(OP_I64_ADD)
        fb.local_get(ly)
        fb.i64_const(12)
        fb.byte(OP_I64_MUL)
        fb.local_get(lm)
        fb.byte(OP_I64_ADD)
        fb.byte(OP_I64_SUB)
        fb.local_set(mdiff)

        fb.i32_const(0)
        fb.local_set(less)

        # day check
        fb.local_get(rd)
        fb.local_get(ld)
        fb.byte(OP_I64_LT_S)
        fb.emit_if()
        fb.i32_const(1)
        fb.local_set(less)
        fb.emit_else()
        fb.local_get(rd)
        fb.local_get(ld)
        fb.byte(OP_I64_EQ)
        fb.emit_if()

        # hour check
        fb.local_get(rh)
        fb.local_get(lh)
        fb.byte(OP_I64_LT_S)
        fb.emit_if()
        fb.i32_const(1)
        fb.local_set(less)
        fb.emit_else()
        fb.local_get(rh)
        fb.local_get(lh)
        fb.byte(OP_I64_EQ)
        fb.emit_if()

        # min check
        fb.local_get(rmi)
        fb.local_get(lmi)
        fb.byte(OP_I64_LT_S)
        fb.emit_if()
        fb.i32_const(1)
        fb.local_set(less)
        fb.emit_else()
        fb.local_get(rmi)
        fb.local_get(lmi)
        fb.byte(OP_I64_EQ)
        fb.emit_if()

        # sec check
        fb.local_get(rs)
        fb.local_get(ls)
        fb.byte(OP_I64_LT_S)
        fb.emit_if()
        fb.i32_const(1)
        fb.local_set(less)
        fb.emit_else()
        fb.local_get(rs)
        fb.local_get(ls)
        fb.byte(OP_I64_EQ)
        fb.emit_if()

        # frac check
        fb.local_get(rfrac)
        fb.local_get(lfrac)
        fb.byte(OP_I64_LT_S)
        fb.emit_if()
        fb.i32_const(1)
        fb.local_set(less)
        fb.emit_end()

        fb.emit_end()
        fb.emit_end()
        fb.emit_end()
        fb.emit_end()
        fb.emit_end()
        fb.emit_end()
        fb.emit_end()
        fb.emit_end()

        fb.local_get(less)
        fb.emit_if()
        fb.local_get(mdiff)
        fb.i64_const(1)
        fb.byte(OP_I64_SUB)
        fb.local_set(mdiff)
        fb.emit_end()

        fb.local_get(mdiff)
        fb.local_get(sign)
        fb.byte(OP_I64_MUL)
        fb.byte(OP_RETURN)
        self.add_code(fb)

