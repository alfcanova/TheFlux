    def build_dt_now(self) -> None:
        fb = FuncBody(0)
        wasi_off = self.cg._dt_wasi_off()
        fb.i32_const(0)
        fb.i64_const(0)
        fb.i32_const(wasi_off)
        _call(fb, self.helpers["$clock_time_get"])
        fb.byte(OP_DROP)
        fb.i32_const(wasi_off)
        _mem(fb, OP_I64_LOAD, 3, 0)
        fb.byte(OP_RETURN)
        self.add_code(fb)

    def build_dt_monotonic_now(self) -> None:
        fb = FuncBody(0)
        wasi_off = self.cg._dt_wasi_off()
        fb.i32_const(1)
        fb.i64_const(0)
        fb.i32_const(wasi_off)
        _call(fb, self.helpers["$clock_time_get"])
        fb.byte(OP_DROP)
        fb.i32_const(wasi_off)
        _mem(fb, OP_I64_LOAD, 3, 0)
        fb.byte(OP_RETURN)
        self.add_code(fb)

