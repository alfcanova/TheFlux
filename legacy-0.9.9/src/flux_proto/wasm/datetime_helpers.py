    def build_dt_format(self) -> None:
        fb = FuncBody(2)
        pptr = fb.new_i32()
        plen = fb.new_i32()
        pi = fb.new_i32()
        out = fb.new_i32()
        oi = fb.new_i32()
        c = fb.new_i32()
        nc = fb.new_i32()

        fb.local_get(0)
        _call(fb, self.helpers["$dt_split"])

        fb.local_get(1)
        fb.i64_const(32)
        fb.byte(OP_I64_SHR_U)
        fb.byte(OP_I32_WRAP_I64)
        fb.local_set(pptr)

        fb.local_get(1)
        fb.i64_const(0xFFFFFFFF)
        fb.byte(OP_I64_AND)
        fb.byte(OP_I32_WRAP_I64)
        fb.local_set(plen)

        fb.local_get(plen)
        fb.i32_const(64)
        fb.byte(OP_I32_ADD)
        _call(fb, self.helpers["$flux_alloc"])
        fb.local_set(out)

        fb.i32_const(0)
        fb.local_set(pi)
        fb.i32_const(0)
        fb.local_set(oi)

        fb.emit_block()
        b_done = fb.label_depth
        fb.emit_loop()
        l_lp = fb.label_depth

        fb.local_get(pi)
        fb.local_get(plen)
        fb.byte(OP_I32_GE_U)
        fb.br_if(_br_depth(fb, b_done))

        fb.local_get(pptr)
        fb.local_get(pi)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD8_U, 0, 0)
        fb.local_set(c)

        # if c == '%' (37) and pi + 1 < plen:
        fb.local_get(c)
        fb.i32_const(37)
        fb.byte(OP_I32_EQ)
        fb.local_get(pi)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.local_get(plen)
        fb.byte(OP_I32_LT_U)
        fb.byte(OP_I32_AND)
        fb.emit_if()

        fb.local_get(pptr)
        fb.local_get(pi)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.byte(OP_I32_ADD)
        _mem(fb, OP_I32_LOAD8_U, 0, 0)
        fb.local_set(nc)

        fb.local_get(pi)
        fb.i32_const(2)
        fb.byte(OP_I32_ADD)
        fb.local_set(pi)

        # %Y: Year (89)
        fb.local_get(nc)
        fb.i32_const(89)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(out)
        fb.local_get(oi)
        fb.byte(OP_I32_ADD)
        fb.global_get(self.g_y)
        _call(fb, self.helpers["$dt_write_4d"])
        fb.local_get(oi)
        fb.i32_const(4)
        fb.byte(OP_I32_ADD)
        fb.local_set(oi)
        fb.br(_br_depth(fb, l_lp))
        fb.emit_end()

        # %m: Month (109)
        fb.local_get(nc)
        fb.i32_const(109)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(out)
        fb.local_get(oi)
        fb.byte(OP_I32_ADD)
        fb.global_get(self.g_m)
        _call(fb, self.helpers["$dt_write_2d"])
        fb.local_get(oi)
        fb.i32_const(2)
        fb.byte(OP_I32_ADD)
        fb.local_set(oi)
        fb.br(_br_depth(fb, l_lp))
        fb.emit_end()

        # %d: Day (100)
        fb.local_get(nc)
        fb.i32_const(100)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(out)
        fb.local_get(oi)
        fb.byte(OP_I32_ADD)
        fb.global_get(self.g_d)
        _call(fb, self.helpers["$dt_write_2d"])
        fb.local_get(oi)
        fb.i32_const(2)
        fb.byte(OP_I32_ADD)
        fb.local_set(oi)
        fb.br(_br_depth(fb, l_lp))
        fb.emit_end()

        # %H: Hour (72)
        fb.local_get(nc)
        fb.i32_const(72)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(out)
        fb.local_get(oi)
        fb.byte(OP_I32_ADD)
        fb.global_get(self.g_h)
        _call(fb, self.helpers["$dt_write_2d"])
        fb.local_get(oi)
        fb.i32_const(2)
        fb.byte(OP_I32_ADD)
        fb.local_set(oi)
        fb.br(_br_depth(fb, l_lp))
        fb.emit_end()

        # %M: Minute (77)
        fb.local_get(nc)
        fb.i32_const(77)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(out)
        fb.local_get(oi)
        fb.byte(OP_I32_ADD)
        fb.global_get(self.g_mi)
        _call(fb, self.helpers["$dt_write_2d"])
        fb.local_get(oi)
        fb.i32_const(2)
        fb.byte(OP_I32_ADD)
        fb.local_set(oi)
        fb.br(_br_depth(fb, l_lp))
        fb.emit_end()

        # %S: Second (83)
        fb.local_get(nc)
        fb.i32_const(83)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(out)
        fb.local_get(oi)
        fb.byte(OP_I32_ADD)
        fb.global_get(self.g_s)
        _call(fb, self.helpers["$dt_write_2d"])
        fb.local_get(oi)
        fb.i32_const(2)
        fb.byte(OP_I32_ADD)
        fb.local_set(oi)
        fb.br(_br_depth(fb, l_lp))
        fb.emit_end()

        # Unknown specifier: write '%' and nc
        fb.local_get(out)
        fb.local_get(oi)
        fb.byte(OP_I32_ADD)
        fb.i32_const(37)
        _mem(fb, OP_I32_STORE8, 0, 0)

        fb.local_get(out)
        fb.local_get(oi)
        fb.i32_const(1)
        fb.byte(OP_I32_ADD)
        fb.byte(OP_I32_ADD)
        fb.local_get(nc)
