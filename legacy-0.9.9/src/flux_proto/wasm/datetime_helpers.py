    def build_dt_days_in_month_val(self) -> None:
        fb = FuncBody(2)
        fb.local_get(1)
        fb.i64_const(2)
        fb.byte(OP_I64_EQ)
        fb.emit_if()
        fb.i64_const(29)
        fb.i64_const(28)
        fb.local_get(0)
        _call(fb, self.helpers["$dt_is_leap_year_val"])
        fb.i64_const(1)
        fb.byte(OP_I64_EQ)
        fb.byte(OP_SELECT)
        fb.byte(OP_RETURN)
        fb.emit_end()

        for m_val in (4, 6, 9, 11):
            fb.local_get(1)
            fb.i64_const(m_val)
            fb.byte(OP_I64_EQ)
            fb.emit_if()
            fb.i64_const(30)
            fb.byte(OP_RETURN)
            fb.emit_end()

        fb.i64_const(31)
        fb.byte(OP_RETURN)
        self.add_code(fb)

    def build_dt_get_comp(self) -> None:
        fb = FuncBody(2)
        y = fb.new_i64()
        m = fb.new_i64()
        d = fb.new_i64()
        w = fb.new_i64()

        fb.local_get(0)
        _call(fb, self.helpers["$dt_split"])
        fb.global_get(self.g_y)
        fb.local_set(y)
        fb.global_get(self.g_m)
        fb.local_set(m)
        fb.global_get(self.g_d)
        fb.local_set(d)

        # 0: year
        fb.local_get(1)
        fb.i32_const(0)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(y)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 1: month
        fb.local_get(1)
        fb.i32_const(1)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(m)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 2: day
        fb.local_get(1)
        fb.i32_const(2)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(d)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 3: hour
        fb.local_get(1)
        fb.i32_const(3)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.global_get(self.g_h)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 4: minute
        fb.local_get(1)
        fb.i32_const(4)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.global_get(self.g_mi)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 5: second
        fb.local_get(1)
        fb.i32_const(5)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.global_get(self.g_s)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 6: millisecond
        fb.local_get(1)
        fb.i32_const(6)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.global_get(self.g_ms)
        fb.i64_const(1000)
        fb.byte(OP_I64_REM_S)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 7: microsecond
        fb.local_get(1)
        fb.i32_const(7)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.global_get(self.g_us)
        fb.i64_const(1000000)
        fb.byte(OP_I64_REM_S)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 8: nanosecond
        fb.local_get(1)
        fb.i32_const(8)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.global_get(self.g_ns)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 9: weekday (Monday=1..Sunday=7)
        fb.local_get(1)
        fb.i32_const(9)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.global_get(self.g_days)
        fb.i64_const(3)
        fb.byte(OP_I64_ADD)
        fb.i64_const(7)
        fb.byte(OP_I64_REM_S)
        fb.local_set(w)
        fb.local_get(w)
        fb.i64_const(0)
        fb.byte(OP_I64_LT_S)
        fb.emit_if()
        fb.local_get(w)
        fb.i64_const(7)
        fb.byte(OP_I64_ADD)
        fb.local_set(w)
        fb.emit_end()
        fb.local_get(w)
        fb.i64_const(1)
        fb.byte(OP_I64_ADD)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 10: dayOfYear
        fb.local_get(1)
        fb.i32_const(10)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.global_get(self.g_days)
        fb.local_get(y)
        fb.i64_const(1)
        fb.i64_const(1)
        _call(fb, self.helpers["$days_from_civil"])
        fb.byte(OP_I64_SUB)
        fb.i64_const(1)
        fb.byte(OP_I64_ADD)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 11: daysInMonth
        fb.local_get(1)
        fb.i32_const(11)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(y)
        fb.local_get(m)
        _call(fb, self.helpers["$dt_days_in_month_val"])
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 12: quarter
        fb.local_get(1)
        fb.i32_const(12)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(m)
        fb.i64_const(1)
        fb.byte(OP_I64_SUB)
        fb.i64_const(3)
        fb.byte(OP_I64_DIV_S)
        fb.i64_const(1)
        fb.byte(OP_I64_ADD)
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 13: isLeapYear
        fb.local_get(1)
        fb.i32_const(13)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(y)
        _call(fb, self.helpers["$dt_is_leap_year_val"])
        fb.byte(OP_RETURN)
        fb.emit_end()

        # 14: isWeekend
        fb.local_get(1)
        fb.i32_const(14)
        fb.byte(OP_I32_EQ)
        fb.emit_if()
        fb.local_get(0)
        fb.i32_const(9)
        _call(fb, self.helpers["$dt_get_comp"])
        fb.local_set(w)
        fb.i64_const(1)
        fb.i64_const(0)
        fb.local_get(w)
        fb.i64_const(6)
        fb.byte(OP_I64_EQ)
        fb.local_get(w)
        fb.i64_const(7)
        fb.byte(OP_I64_EQ)
        fb.byte(OP_I32_OR)
        fb.byte(OP_SELECT)
        fb.byte(OP_RETURN)
        fb.emit_end()

        fb.i64_const(0)
        fb.byte(OP_RETURN)
        self.add_code(fb)

