    def build_dt_add_months(self) -> None:
        fb = FuncBody(2)
        y = fb.new_i64()
        m = fb.new_i64()
        d = fb.new_i64()
        h = fb.new_i64()
        mi = fb.new_i64()
        s = fb.new_i64()
        frac = fb.new_i64()
        tot_m = fb.new_i64()
        ny = fb.new_i64()
        nm = fb.new_i64()
        dim = fb.new_i64()
        nd = fb.new_i64()
        day = fb.new_i64()
        sec = fb.new_i64()

        fb.local_get(0)
        _call(fb, self.helpers["$dt_split"])
        fb.global_get(self.g_y)
        fb.local_set(y)
        fb.global_get(self.g_m)
        fb.local_set(m)
        fb.global_get(self.g_d)
        fb.local_set(d)
        fb.global_get(self.g_h)
        fb.local_set(h)
        fb.global_get(self.g_mi)
        fb.local_set(mi)
        fb.global_get(self.g_s)
        fb.local_set(s)
        fb.global_get(self.g_ns)
        fb.local_set(frac)

        # tot_m = y * 12 + (m - 1) + months
        fb.local_get(y)
        fb.i64_const(12)
        fb.byte(OP_I64_MUL)
        fb.local_get(m)
        fb.i64_const(1)
        fb.byte(OP_I64_SUB)
        fb.byte(OP_I64_ADD)
        fb.local_get(1)
        fb.byte(OP_I64_ADD)
        fb.local_set(tot_m)

        # ny = dt_floor_div(tot_m, 12)
        fb.local_get(tot_m)
        fb.i64_const(12)
        _call(fb, self.helpers["$dt_floor_div"])
        fb.local_set(ny)

        # nm = dt_floor_rem(tot_m, 12) + 1
        fb.local_get(tot_m)
        fb.i64_const(12)
        _call(fb, self.helpers["$dt_floor_rem"])
        fb.i64_const(1)
        fb.byte(OP_I64_ADD)
        fb.local_set(nm)

        # dim = dt_days_in_month_val(ny, nm)
        fb.local_get(ny)
        fb.local_get(nm)
        _call(fb, self.helpers["$dt_days_in_month_val"])
        fb.local_set(dim)

        # nd = select(dim, d, d > dim)
        fb.local_get(dim)
        fb.local_get(d)
        fb.local_get(d)
        fb.local_get(dim)
        fb.byte(OP_I64_GT_S)
        fb.byte(OP_SELECT)
        fb.local_set(nd)

        # day = days_from_civil(ny, nm, nd)
        fb.local_get(ny)
        fb.local_get(nm)
        fb.local_get(nd)
        _call(fb, self.helpers["$days_from_civil"])
        fb.local_set(day)

        # sec = day * 86400 + h * 3600 + mi * 60 + s
        fb.local_get(day)
        fb.i64_const(86400)
        fb.byte(OP_I64_MUL)
        fb.local_get(h)
        fb.i64_const(3600)
        fb.byte(OP_I64_MUL)
        fb.byte(OP_I64_ADD)
        fb.local_get(mi)
        fb.i64_const(60)
        fb.byte(OP_I64_MUL)
        fb.byte(OP_I64_ADD)
        fb.local_get(s)
        fb.byte(OP_I64_ADD)
        fb.local_set(sec)

        # return sec * 1000000000 + frac
        fb.local_get(sec)
        fb.i64_const(1000000000)
        fb.byte(OP_I64_MUL)
        fb.local_get(frac)
        fb.byte(OP_I64_ADD)
        fb.byte(OP_RETURN)
